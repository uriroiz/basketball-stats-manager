const assert = require('assert');
const load = require('./helpers/broadcast');
const c = load(['ibba_seasons', 'ibba_analysis_scope', 'ibba_window_stats', 'ibba_rich_insights', 'ibba_broadcast_copy', 'ibba_broadcast_view', 'ibba_insights_v2']);
const S = c.window.IBBAAnalysisScope;
assert(S, 'analysis scope service exists');
const game = (id, key = '2025-26') => ({gameId:id, seasonKey:key, date:'2026-01-01'});
const snapshot = (key, count=5) => ({entityRef:'1', seasonKeys:[key], gamesPlayed:2,coverage:{complete:true},
  window:{spec:{seasonKey:key, phase:'any', mode:'recent', count}, resultGames:[game(1,key),game(2,key)]},
  metrics:{ftPercentage:{gameCount:2,numerator:13,denominator:20,gameIds:['1','2'],value:65}}, quarterMargins:[]});
const scope = S.fromSnapshots([snapshot('2025-26')], {facts:{metric:'ftPercentage'}, asOf:'2026-01-02'});
assert.strictEqual(scope.phase, 'all');
assert.strictEqual(scope.mode, 'recent');
assert.strictEqual(scope.windows[0].count, 5);
assert.strictEqual(scope.metricSamples[0].gameCount, 2);
assert.strictEqual(scope.metricSamples[0].denominator, 20, 'attempt denominator differs from game count');
assert.strictEqual(scope.metricSamples[0].gameRefs.length, 2);
const official = S.forOfficialSummary({games:30,metrics:{ftPercentage:65}}, {seasonKey:'2025-26',entityRef:'1'});
assert.strictEqual(official.phase, 'regular');
assert.strictEqual(official.basis, 'officialSummary');
assert.notStrictEqual(S.groupKey(scope), S.groupKey(official));
const older = S.fromSnapshots([snapshot('2024-25')], {facts:{metric:'ftPercentage'}});
assert.strictEqual(S.groupKey(older), S.groupKey(scope), 'same relative window compares across season columns');
const comparison = S.fromSnapshots([snapshot('2025-26'), snapshot('2024-25')], {facts:{metric:'ftPercentage'}});
assert.strictEqual(comparison.windows.length, 2);
assert.strictEqual(comparison.metricSamples.length, 2);
const unknown = S.fromGames([game(1)], {phase:'unknown',mode:'single'});
assert.strictEqual(unknown.phase, 'unknown');
assert(!S.label(unknown).includes('העונה הסדירה'));
assert(S.label(official).includes('העונה הסדירה'));
const full = S.fromSnapshots([snapshot('2025-26',null)], {facts:{metric:'ftPercentage'}});
assert.strictEqual(full.mode, 'season');
assert(S.label(full).includes('כל משחקי העונה'));
const rich = c.window.IBBARichInsights.story('WINDOW_STYLE','PROFILE',{teamId:1,name:'A'},[snapshot('2025-26')],{metric:'ftPercentage',value:65});
assert(rich.analysisScope, 'source producer attaches scope');
const story = (analysisScope, value, n) => ({type:'WINDOW_STYLE',teamIds:[1],teamName:'A',seasonKeys:['2025-26'],analysisScope,sampleSize:n,facts:{metric:'ftPercentage',value}});
const V = c.window.IBBABroadcastView;
assert.strictEqual(V.groups([story(full,65,2), story(official,65,30)]).length, 2);
const table = V.renderGroups([story(full,65,2), {...story(full,70,1),facts:{metric:'points',value:70}}]);
assert(table.includes('2</bdi> משחקים') && table.includes('1</bdi> משחק'), 'different metric counts remain explicit');
assert.strictEqual(V.groups([story(unknown,65,2),story(unknown,60,1)]).length,2, 'unverified scopes stay individual');
const played=Array.from({length:8},(_,i)=>({...game(i+1,'2026-27'),date:`2026-10-${i+1}`,teams:[{teamId:1,name:'A',score:80,isHome:true},{teamId:2,name:'B',score:70}],players:[{playerId:7,teamName:'A',stats:{points:i<4?10:20}}]}));
const rising=new c.window.IBBAInsightsV2({getTeamAverages:()=>[]}).detectRisingStar('A',played);
assert.strictEqual(rising.analysisScope.windows.length,2, 'legacy detector describes the two actual player halves');
assert.strictEqual(rising.analysisScope.windows[0].gameRefs.length,4);
assert.strictEqual(rising.analysisScope.windows[1].gameRefs[0].gameId,'5');
assert.strictEqual(rising.analysisScope.metricSamples[0].gameRefs[0].gameId,'1');
assert.strictEqual(rising.playerId,7,'legacy rising player carries official identity');
console.log('analysis scope tests passed');
